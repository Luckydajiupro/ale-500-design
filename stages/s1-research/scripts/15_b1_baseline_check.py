#!/usr/bin/env python3
"""S1-02B1 U1 — read-only baseline consistency check.

Loads the S1-01 final taxonomy mapping and the S1-02A effective view as
READ-ONLY inputs, runs the checks demanded by the B1 brief, and writes only
this round's own report (S1_02B1_BASELINE_CONSISTENCY_REPORT.md).

Checks:
  B0  Re-run the A-round validator (scripts/14_validate_effective_view.py).
      Its positive 7 checks + 7 negative self-tests are the authoritative gate
      proving the 51-row baseline is still in the state A validated.
  B1  All 13 B1 target subdomains exist in S1_01_CATEGORY_MAPPING.csv
      (matched on subdomain_id + subdomain_code).
  B2  The effective view holds 0 candidates inside B1 territory
      (subdomain_code prefixed phys_/life_/med_). Expected: B1 is fresh
      territory, so its dedup check is vs the 51 A candidates, not itself.
  B3  HEC-RAS stored phrasing vs the independent-review-verified facts.
      A conflict is REPORTED as a finding, never fixed here (A files are
      read-only, and the review facts are authoritative for B1 documents).
      Agreement items are also stated, so the finding is precisely bounded.
  B4  Per-column completeness of the 51 effective rows (informative).

Negative self-tests mutate in-memory copies and assert the specific B1 check
flips FAIL, mirroring the A-validator pattern.
"""
import csv, sys, subprocess, hashlib, datetime

WS = "/Users/mac/Workspaces/ale-研究设计/ale-500-category-research"
MAPPING = f"{WS}/S1_01_CATEGORY_MAPPING.csv"
EFF = f"{WS}/S1_02A_EFFECTIVE_CANDIDATES.csv"
WC = f"{WS}/S1_02A_WORKFLOW_CANDIDATES.csv"
DUP = f"{WS}/S1_02A_DUPLICATE_ATTRIBUTION.csv"
REPORT = f"{WS}/S1_02B1_BASELINE_CONSISTENCY_REPORT.md"

# Independent-review-verified facts (authoritative for B1, from the B1 brief).
REVIEW_HEC_RAS = (
    "Review-verified: HEC-RAS Classic 7.0.2 has a Linux-compiled compute engine; "
    "RAS 2025 Beta supports Linux headless compute but is not production-suitable; "
    "Tencent-cloud server run state remains NOT_VERIFIED."
)

# B1 targets (subdomain_id, subdomain_code) in S1_01_CATEGORY_MAPPING.csv.
B1_TARGETS = [
    ("2.1", "physics"), ("2.2", "chemistry_materials"), ("2.3", "astronomy"),
    ("2.4", "earth_atmo"),
    ("3.1", "biomolecular"), ("3.2", "genomics"), ("3.3", "cell_imaging"),
    ("3.4", "systems_microbial"),
    ("4.1", "clinical_diagnostics"), ("4.2", "therapeutic_oncology"),
    ("4.3", "clinical_informatics"), ("4.4", "public_health"),
    ("4.5", "clinical_trials"),
]

def load(path):
    with open(path, encoding="utf-8") as f:
        return list(csv.DictReader(f))

def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()[:16]

def b3_check(rows):
    """Evaluate the HEC-RAS stored-vs-review comparison. Returns
    (ok, findings, agreements)."""
    hec = [r for r in rows
           if "hec-ras" in (r["workflow_title"] + " " + r["primary_claim"]).lower()]
    findings, agreements, ok = [], [], True
    if not hec:
        return False, ["FAIL: no HEC-RAS row found in the effective view."], []
    text = " ".join(r["primary_claim"] + " " + r["workflow_summary"]
                    for r in hec).lower()
    classic_claim = "no official" in text
    ras_claim = "native linux" in text
    nv_claim = all(r["linux_verification_state"] == "NOT_VERIFIED" for r in hec)
    if classic_claim:
        findings.append(
            "CONFLICT (report-only): stored A text asserts the HEC-RAS classic "
            "line has NO official native Linux, while the independent review "
            "verified Classic 7.0.2 HAS a Linux-compiled compute engine. "
            "The two statements name different components (GUI/distribution vs "
            "compute engine); the review fact is authoritative for B1 documents. "
            "Neither file is modified by B1.")
    if ras_claim:
        agreements.append("AGREE: stored text carries the RAS 2025 native-Linux "
                          "+ headless-CLI and not-production-suitable wording.")
    else:
        ok = False
        findings.append("FAIL: stored HEC-RAS text lacks the RAS 2025 "
                        "native-Linux headless wording.")
    if nv_claim:
        agreements.append(f"AGREE: all {len(hec)} HEC-RAS rows keep "
                          "linux_verification_state=NOT_VERIFIED.")
    else:
        ok = False
        findings.append("FAIL: a HEC-RAS row is not NOT_VERIFIED.")
    agreements.append(f"HEC-RAS rows: {sorted(set(r['candidate_id'] for r in hec))}")
    return ok, findings, agreements

def main():
    lines = ["# S1-02B1 Baseline Consistency Report",
             f"\nGenerated by scripts/15_b1_baseline_check.py at "
             f"{datetime.datetime.now().isoformat(timespec='seconds')}.\n",
             "This report is an S1-02B1 deliverable. All S1-01/S1-02A inputs "
             "were opened read-only; checksums prove the inputs were not "
             "modified by this run.\n"]
    report_ok = True

    before = {p: sha256(p) for p in (MAPPING, EFF, WC, DUP)}

    # B0: re-run the A validator.
    proc = subprocess.run([sys.executable, f"{WS}/scripts/14_validate_effective_view.py"],
                          capture_output=True, text=True, cwd=WS)
    b0 = proc.returncode == 0
    report_ok &= b0
    lines += ["## B0 Re-run of A-round validator (scripts/14_validate_effective_view.py)",
              f"PASS: exit code 0" if b0 else f"FAIL: exit code {proc.returncode}",
              "", "```", proc.stdout.strip(), "```", ""]

    eff = load(EFF)
    mapping = load(MAPPING)

    # B1: 13 target subdomains present (id + code).
    have = {(r["subdomain_id"], r["subdomain_code"]) for r in mapping}
    missing = [t for t in B1_TARGETS if t not in have]
    b1 = not missing
    report_ok &= b1
    lines += ["## B1 The 13 B1 target subdomains in S1_01_CATEGORY_MAPPING.csv",
              f"PASS: all 13 present (subdomain_id+subdomain_code)"
              if b1 else f"FAIL: missing {missing}", ""]

    # B2: zero A coverage inside B1 territory.
    ids = [r["candidate_id"] for r in eff]
    inside = [i for i in ids if i.startswith(("phys_", "life_", "med_"))]
    b2 = not inside
    report_ok &= b2
    lines += ["## B2 A-round coverage inside B1 territory (expected none)",
              f"PASS: 0 candidate ids prefixed phys_/life_/med_ among {len(ids)} rows"
              if b2 else f"FAIL: {inside}", ""]

    # B3: HEC-RAS stored phrasing vs review facts.
    b3, findings, agreements = b3_check(eff)
    report_ok &= b3
    lines += ["## B3 HEC-RAS stored phrasing vs review-verified facts",
              REVIEW_HEC_RAS, ""]
    lines += [f"- {f}" for f in findings]
    lines += [f"- {a}" for a in agreements]
    lines += [""]

    # B4: per-column completeness.
    cols = list(eff[0].keys())
    empty = {c: sum(1 for r in eff if not str(r[c]).strip()) for c in cols}
    empties = {c: n for c, n in empty.items() if n}
    lines += ["## B4 Per-column completeness of the 51 effective rows",
              f"columns={len(cols)} rows={len(eff)}"]
    lines += [f"- empty cells: {c}={n}" for c, n in sorted(empties.items())] or ["- none"]

    after = {p: sha256(p) for p in before}
    unchanged = before == after
    report_ok &= unchanged
    lines += ["", "## Input integrity (read-only proof)",
              f"{'PASS' if unchanged else 'FAIL'}: sha256 fingerprints unchanged "
              f"over the run", ""]

    # Negative self-tests for the B1 additions.
    lines += ["## Negative self-tests (mutated in-memory copies must flip FAIL)"]
    neg_ok = True

    eff_copy = [dict(r) for r in eff]
    eff_copy.append(dict(eff[0], candidate_id="phys_fake_wf01"))
    inside_now = [i for i in (r["candidate_id"] for r in eff_copy)
                  if i.startswith(("phys_", "life_", "med_"))]
    neg1 = bool(inside_now)
    neg_ok &= neg1
    lines += [f"- {'PASS' if neg1 else 'FAIL'} B2 flips when a phys_ row is injected"]

    mapping_copy = [r for r in mapping
                    if (r["subdomain_id"], r["subdomain_code"]) != ("2.1", "physics")]
    have_now = {(r["subdomain_id"], r["subdomain_code"]) for r in mapping_copy}
    neg2 = any(t not in have_now for t in B1_TARGETS)
    neg_ok &= neg2
    lines += [f"- {'PASS' if neg2 else 'FAIL'} B1 flips when a target mapping row is dropped"]

    # B3 gate flips: (a) verified-state injected into a HEC row, (b) RAS wording removed.
    mut = [dict(r) for r in eff]
    for r in mut:
        if "hec-ras" in (r["workflow_title"] + " " + r["primary_claim"]).lower():
            r["linux_verification_state"] = "VERIFIED"
            break
    neg3a, _, _ = b3_check(mut)
    neg3a = not neg3a
    neg_ok &= neg3a
    lines += [f"- {'PASS' if neg3a else 'FAIL'} B3 flips when a HEC-RAS row is marked VERIFIED"]

    mut = [dict(r) for r in eff]
    for r in mut:
        if "hec-ras" in (r["workflow_title"] + " " + r["primary_claim"]).lower():
            r["primary_claim"] = r["primary_claim"].replace("native Linux", "Windows-only")
    neg3b, _, _ = b3_check(mut)
    neg3b = not neg3b
    neg_ok &= neg3b
    lines += [f"- {'PASS' if neg3b else 'FAIL'} B3 flips when the RAS native-Linux wording is removed"]

    report_ok &= neg_ok
    lines += ["", f"## Overall U1: {'PASS' if report_ok else 'FAIL'}", ""]

    with open(REPORT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("\n".join(lines))
    print(f"\nU1 OVERALL={'PASS' if report_ok else 'FAIL'}")
    raise SystemExit(0 if report_ok else 1)

if __name__ == "__main__":
    main()