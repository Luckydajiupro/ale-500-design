#!/usr/bin/env python3
"""S1-02B2 Phase-0 precheck (T1) — read-only gate over the frozen S1-01 / S1-02A / S1-02B1 inputs.

Loads every frozen input READ-ONLY, proves read-only via sha256 manifest, re-runs the two
authoritative prior validators, checks B1 downstream integrity for the five review facets the
brief names (结构错误 / 重复ID / 无依据的专业结论 / 伦理字段缺漏 / 敏感信息泄露风险), and
carries the 5 open B1 review items forward verbatim.

Writes ONLY S1-02B2 working outputs under evidence/s1_02b2_research/:
  phase0_input_manifest.json   sha256 manifest the end-of-batch validator re-checks
  b1_open_review_items.md      the 5 B1 items, verbatim + source line + status
  phase0_precheck.md           the report below

Exit 0 iff every BLOCK gate passes. FINDING rows (B1-integrity gaps) are recorded and carried
to the B2 risk register but do not block; a material blocker prints BLOCK and the run stops there.
"""
import csv, hashlib, json, os, re, subprocess, sys, datetime
from collections import Counter

WS = "/Users/mac/Workspaces/ale-研究设计/ale-500-category-research"
OUT_DIR = f"{WS}/evidence/s1_02b2_research"
MANIFEST = f"{OUT_DIR}/phase0_input_manifest.json"
CARRIED = f"{OUT_DIR}/b1_open_review_items.md"
REPORT = f"{OUT_DIR}/phase0_precheck.md"

FROZEN = [
    "S1_01_CATEGORY_MAPPING.csv",
    "S1_02A_EFFECTIVE_CANDIDATES.csv",
    "S1_02B1_WORKFLOW_CANDIDATES.csv",
    "S1_02B1_SOURCE_CLAIM_MAP.csv",
    "S1_02B1_REVIEW_SUMMARY.md",
    "S1_02B1_DUPLICATE_ATTRIBUTION.md",
    "S1_02B1_BASELINE_CONSISTENCY_REPORT.md",
]

B2_TARGETS = [
    ("5.1", "comp_neuro"), ("5.2", "exp_psychology"),
    ("6.1", "accounting"), ("6.2", "actuarial_risk"),
    ("6.3", "enterprise_analytics"), ("6.4", "compliance"),
    ("6.5", "hr_pm"), ("6.6", "sales_marketing"),
    ("6.7", "quant_finance"), ("6.8", "supply_chain"),
    ("13.1", "economics"),
]
B2_ID_PREFIXES = ("psy_", "biz_", "soc_")

# The 5 open review items carried from S1_02B1_REVIEW_SUMMARY.md, preserved verbatim.
# (source file, section title, item number, verbatim text)
B1_OPEN_ITEMS = [
    ("S1_02B1_REVIEW_SUMMARY.md", "独立评审需要确认的条目", 1,
     "HEC-RAS classic 线 Linux 引擎的表述差异只在报告层面记录，是否需要在后续阶段"
     "「回写修订」S1-02A 有效视图（本阶段按规则未动）。"),
    ("S1_02B1_REVIEW_SUMMARY.md", "独立评审需要确认的条目", 2,
     "全部 Linux 运行验证均未执行（57/57 NOT_VERIFIED），评审是否接受其为 B1 交付状态。"),
    ("S1_02B1_REVIEW_SUMMARY.md", "独立评审需要确认的条目", 3,
     "5 个跨领域相邻对全部否决重复的裁定（E4 级）需要专家背书。"),
    ("S1_02B1_REVIEW_SUMMARY.md", "独立评审需要确认的条目", 4,
     "E3 证据链中的付费墙/受限披露缺口（ISO、EGA/dbGaP、ESMO/Elsevier 全文机构访问限制、"
     "TransCelerate 403 等）是否满足验收标准。"),
    ("S1_02B1_REVIEW_SUMMARY.md", "独立评审需要确认的条目", 5,
     "伦理字段均由来源推演得出，而未经过机构伦理委员会复核（本阶段不在授权范围内）。"),
]

EVIDENCE_KINDS = {"industry_standard_complete", "tool_existence",
                  "agent_inferred_combination", "expert_pending_proposal"}
EVIDENCE_LEVELS = {"E1", "E2", "E3", "E4"}
NO_STANDARD_CLAIM_FROM = {"vendor_doc", "vendor_blog", "government_tool_page"}
ETHICS_COLS = ["data_usage_authorization", "privacy_considerations",
               "research_ethics", "reproducibility_assessment"]

EMAIL_RE = re.compile(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}")
PHONE_RE = re.compile(r"(\+?\d[\d\s().-]{6,}\d)")
ID_DIGIT_RE = re.compile(r"\b\d{9,}\b")
SENSITIVE_TOKENS = ("SSN", "passport", "身份证", "病历号", "患者ID", "credit card",
                    "卡号", "账号密码")

def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()

def load(path):
    with open(path, encoding="utf-8") as f:
        return list(csv.DictReader(f))

def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    lines = ["# S1-02B2 Phase-0 precheck",
             f"\nGenerated by scripts/20_b2_precheck.py at "
             f"{datetime.datetime.now().isoformat(timespec='seconds')}.",
             "\nRead-only gate over S1-01 / S1-02A / S1-02B1. Writes only "
             "S1-02B2 working outputs under evidence/s1_02b2_research/.\n"]
    blocked = False

    # G0 sha256 manifest
    manifest = {p: {"sha256": sha256(f"{WS}/{p}"), "size": os.path.getsize(f"{WS}/{p}")}
                for p in FROZEN}
    with open(MANIFEST, "w", encoding="utf-8") as f:
        json.dump(manifest, f, ensure_ascii=False, indent=2, sort_keys=True)
    lines += ["## G0 Input manifest (read-only proof at batch start)",
              f"PASS: sha256 captured for {len(FROZEN)} frozen inputs."]
    lines += [f"- {p} {v['sha256'][:16]}" for p, v in sorted(manifest.items())]
    lines += [""]

    # G1 re-run the two authoritative prior validators (14 reads A files, 17 reads B1 files).
    procs = {}
    ok = True
    for script, label in (
            (f"{WS}/scripts/14_validate_effective_view.py", "S1-02A effective-view validator"),
            (f"{WS}/scripts/17_validate_b1.py", "S1-02B1 validator")):
        proc = subprocess.run([sys.executable, script], capture_output=True, text=True, cwd=WS)
        procs[label] = proc
        ok &= proc.returncode == 0
    lines += ["## G1 Re-run of the authoritative prior validators"]
    for label, proc in procs.items():
        state = "PASS" if proc.returncode == 0 else "BLOCK"
        if proc.returncode != 0:
            blocked = True
        lines += [f"{state}: {label} exit {proc.returncode}",
                  "```", proc.stdout.strip()[-2000:], "```"]
    lines += [""]

    # G2 the 11 B2 target subdomains exist in the official S1-01 mapping
    mapping = load(f"{WS}/S1_01_CATEGORY_MAPPING.csv")
    have = {(r["subdomain_id"], r["subdomain_code"]) for r in mapping}
    missing = [t for t in B2_TARGETS if t not in have]
    ok = not missing
    if missing:
        blocked = True
    lines += ["## G2 The 11 B2 target subdomains in S1_01_CATEGORY_MAPPING.csv",
              ("PASS: all 11 present (subdomain_id+subdomain_code)"
               if ok else f"BLOCK: missing {missing}"), ""]

    # G3 fresh territory: A and B1 candidate sets hold no psy_/biz_/soc_ ids
    a = load(f"{WS}/S1_02A_EFFECTIVE_CANDIDATES.csv")
    b1 = load(f"{WS}/S1_02B1_WORKFLOW_CANDIDATES.csv")
    a_ids = [r["candidate_id"] for r in a]
    b1_ids = [r["candidate_id"] for r in b1]
    inside = [i for i in a_ids + b1_ids if i.startswith(B2_ID_PREFIXES)]
    ok = not inside
    if inside:
        blocked = True
    lines += ["## G3 A/B1 coverage inside B2 territory (expected none)",
              f"{'PASS' if ok else 'BLOCK'}: "
              f"{len(a_ids) + len(b1_ids)} prior ids checked, "
              f"psy_/biz_/soc_ prefixed={inside}", ""]

    # G4 B1 downstream integrity: the five review facets named in the brief.
    findings = []
    g4_ok = True
    sc = load(f"{WS}/S1_02B1_SOURCE_CLAIM_MAP.csv")

    dup_ids = [i for i, n in Counter(b1_ids).items() if n > 1]
    if dup_ids:
        findings.append(f"duplicate candidate_id in B1 workflow file: {sorted(dup_ids)}")
        g4_ok = False

    sc_ids = [r["candidate_id"] for r in sc]
    sym = sorted(set(b1_ids) ^ set(sc_ids))
    if sym or len(sc_ids) != len(b1_ids):
        findings.append(f"B1 source-claim map not 1:1 with workflow: sym_diff={sym}")
        g4_ok = False

    ethics_bad, e3_bad, gate_bad = [], [], []
    for r in b1:
        sid = r["candidate_id"]
        if sid.startswith(("life_", "med_")):
            for e in ETHICS_COLS:
                if not r[e].strip():
                    ethics_bad.append(f"{sid}.{e}")
        if r["evidence_level"] == "E3" and not r["pending_confirmation"].strip():
            e3_bad.append(sid)
        # P4/P5 re-gate (evidence discipline, re-checked at read time)
        if r["evidence_kind"] not in EVIDENCE_KINDS:
            gate_bad.append(f"{sid} kind={r['evidence_kind']!r}")
        if r["evidence_level"] not in EVIDENCE_LEVELS:
            gate_bad.append(f"{sid} level={r['evidence_level']!r}")
        if (r["evidence_kind"] == "expert_pending_proposal") != (r["evidence_level"] == "E4"):
            gate_bad.append(f"{sid} E4<->expert_pending_proposal pairing")
        if (r["evidence_kind"] == "industry_standard_complete"
                and r["source_category"] in NO_STANDARD_CLAIM_FROM):
            gate_bad.append(f"{sid} ISC backed by {r['source_category']}")
        if not r["primary_source_url"].startswith("http"):
            gate_bad.append(f"{sid} url={r['primary_source_url']!r}")
        if not r["primary_claim"].strip():
            gate_bad.append(f"{sid} empty primary_claim")
    proven = []
    for r in ethics_bad:
        proven.append(f"ethics gap {r}")
        g4_ok = False
    for s in e3_bad:
        proven.append(f"E3 row {s} lacks the mandatory pending_confirmation (no-basis risk)")
        g4_ok = False
    for b in gate_bad:
        proven.append(f"evidence-gate violation {b}")
        g4_ok = False
    findings += proven

    # Sensitive-information leak scan across the two B1 CSV deliverables
    leak_hits = []
    for p, cols in ((f"{WS}/S1_02B1_WORKFLOW_CANDIDATES.csv", None),
                    (f"{WS}/S1_02B1_SOURCE_CLAIM_MAP.csv", None)):
        with open(p, encoding="utf-8") as f:
            text = f.read()
        n_em = len(EMAIL_RE.findall(text))
        n_ph = len(PHONE_RE.findall(text))
        n_dg = len(ID_DIGIT_RE.findall(text))
        toks = [t for t in SENSITIVE_TOKENS if t.lower() in text.lower()]
        if n_em or n_ph or n_dg or toks:
            leak_hits.append(f"{os.path.basename(p)}: emails={n_em} phones-ish={n_ph} "
                             f"digit-runs={n_dg} tokens={toks}")
    lines += ["## G4 B1 downstream integrity (five review facets)",
              f"{'PASS' if g4_ok else 'FINDING'}: dup-ids, source-claim join, ethics, "
              "evidence gates re-checked on all B1 rows."]
    if findings:
        lines += ["Findings (carried to B2 risk register, B1 frozen files NOT modified):"]
        lines += ["- " + x for x in findings][:40]
    else:
        lines += ["- no findings"]
    lines += ["Sensitive-info scan (emails / phone-like / 9+ digit runs / PII tokens):"]
    lines += ["- " + h for h in leak_hits] or ["- no hits in either B1 CSV"]
    lines += [""]

    # G5 carry the 5 B1 open review items verbatim
    carry_lines = ["# S1-02B1 open review items carried into S1-02B2 (verbatim)",
                   "\nCarried unmodified from the B1 review summary. Not marked resolved "
                   "by S1-02B2. Status stays open until independent review decides.",
                   "Source: S1_02B1_REVIEW_SUMMARY.md, section 独立评审需要确认的条目.\n"]
    presence_ok = True
    summary_text = open(f"{WS}/S1_02B1_REVIEW_SUMMARY.md", encoding="utf-8").read()
    for src, sec, num, text in B1_OPEN_ITEMS:
        probe = text[:24]
        present = probe in summary_text
        presence_ok &= present
        carry_lines += [f"{num}. {text}", f"   status: carried-open | evidence: {src} (待独立评审)", ""]
    with open(CARRIED, "w", encoding="utf-8") as f:
        f.write("\n".join(carry_lines))
    if not presence_ok:
        blocked = True
    lines += ["## G5 The 5 B1 review items carried verbatim",
              f"{'PASS' if presence_ok else 'BLOCK'}: all 5 located in "
              "S1_02B1_REVIEW_SUMMARY.md and written to b1_open_review_items.md "
              "with status carried-open, not resolved.", ""]

    # Negative self-tests: mutations must flip their guard
    lines += ["## Negative self-tests (mutated in-memory copies must flip the guard)"]
    neg_ok = True

    mapping_copy = [r for r in mapping
                    if (r["subdomain_id"], r["subdomain_code"]) != ("6.1", "accounting")]
    neg1 = not all(t in {(r["subdomain_id"], r["subdomain_code"]) for r in mapping_copy}
                   for t in B2_TARGETS)
    neg_ok &= neg1
    lines += [f"- {'PASS' if neg1 else 'FAIL'} G2 flips when a target mapping row is dropped"]

    a_copy = [dict(r) for r in a]
    a_copy[0]["candidate_id"] = "biz_fake_wf01"
    neg2 = bool([i for i in a_ids + [a_copy[0]["candidate_id"]] if i.startswith(B2_ID_PREFIXES)])
    neg_ok &= neg2
    lines += [f"- {'PASS' if neg2 else 'FAIL'} G3 flips when a biz_ id is injected into A"]

    b1_copy = [dict(r) for r in b1]
    for r in b1_copy:
        if r["evidence_level"] == "E3":
            r["pending_confirmation"] = ""
            break
    neg3 = bool([r for r in b1_copy
                 if r["evidence_level"] == "E3" and not r["pending_confirmation"].strip()])
    neg_ok &= neg3
    lines += [f"- {'PASS' if neg3 else 'FAIL'} G4 flips when an E3 row loses pending_confirmation"]

    tampered = dict(manifest)
    first = next(iter(tampered))
    tampered[first] = dict(tampered[first], sha256="de" * 32)
    neg4 = not json.dumps(tampered, sort_keys=True) == json.dumps(manifest, sort_keys=True)
    neg_ok &= neg4
    lines += [f"- {'PASS' if neg4 else 'FAIL'} manifest tamper is detectable"]

    overall = (not blocked) and g4_ok
    lines += ["", f"## Phase-0 gate: {'PASS' if overall else 'BLOCK'}", ""]
    with open(REPORT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("\n".join(lines))
    print(f"\nPHASE0={'PASS' if overall else 'BLOCK'}")
    return 0 if overall else 1

if __name__ == "__main__":
    sys.exit(main())